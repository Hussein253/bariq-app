/**
 * بوابات الدفع الإلكتروني — الحالة: غير مُنفَّذة بعد
 * ==================================================
 * ما كان هنا قبل هذا الملف: وحدتان (zaincash.ts و qicard.ts) تبدوان تكاملاً
 * حياً وهما محاكاة كاملة — لا نداء شبكة واحد إلى أي بوابة، وروابط دفع
 * مركَّبة نصياً، و verifyPayment يفكّ Base64 ويعيد success=true دائماً،
 * وأسرار افتراضية مكتوبة في الكود تعمل في الإنتاج بصمت.
 *
 * في نظام يلمس أموال تجار، "يبدو أنه يعمل" أسوأ من "لا يعمل": الأول يسجّل
 * مبالغ لم تُحصَّل. لذلك أُزيلت المحاكاة بالكامل بدل تركها خلف علم تشغيل.
 *
 * ما يلزم لتفعيل زين كاش فعلياً (لا يُخمَّن أي منها — بند ٢-أ في CLAUDE.md):
 *   1. عقد تاجر فعّال + merchantId و secret و msisdn من زين كاش.
 *   2. توثيق نقطة /transaction/init الرسمي: الحقول المطلوبة بالضبط،
 *      وخوارزمية توقيع الـ JWT، ومدة الصلاحية.
 *   3. شكل استجابة /transaction/get وقيم حقل status المحتملة كلها.
 *   4. آلية إشعار الخادم (Server-to-Server callback) وترويسة توقيعه —
 *      الاعتماد على رجوع المتصفح وحده يعني أن الزبون يستطيع تزوير النتيجة.
 *
 * وكذلك لكي كارد: معرّف التاجر والطرفية، ومواصفة 3-D Secure، وشكل الإيصال.
 *
 * وقبل كل ذلك: جدول معاملات في قاعدة البيانات. لا يوجد اليوم أي جدول
 * payments/transactions في المخطط الحي — المعاملات كانت تُخزَّن في الذاكرة
 * وتضيع عند أول إعادة نشر.
 */

export interface PaymentsStatus {
  configured: false
  reason: string
  missing: string[]
}

/**
 * الحالة الحالية دائماً "غير مهيّأة". هذه ليست قراءة لمتغيّرات البيئة:
 * لا يوجد كود تكامل ليُهيّأ. تُستبدل الدالة عند بناء التكامل الحقيقي.
 */
export function paymentsStatus(): PaymentsStatus {
  return {
    configured: false,
    reason: 'تكامل بوابات الدفع الإلكتروني غير مبنيّ بعد',
    missing: [
      'بيانات اعتماد تاجر حقيقية من زين كاش (merchantId, secret, msisdn)',
      'التوثيق الرسمي لنقاط /transaction/init و /transaction/get وشكل الاستجابة',
      'إشعار خادم-إلى-خادم موقَّع من البوابة (لا الاعتماد على رجوع المتصفح)',
      'جدول معاملات دائم في قاعدة البيانات مع مفتاح منع تكرار',
    ],
  }
}

/** رد موحّد ٥٠١ للمسارات التي تعتمد على الدفع الإلكتروني. */
export function paymentsNotImplemented(): Response {
  const status = paymentsStatus()
  return new Response(
    JSON.stringify({
      success: false,
      error: status.reason,
      required: status.missing,
    }),
    { status: 501, headers: { 'content-type': 'application/json; charset=utf-8' } }
  )
}
