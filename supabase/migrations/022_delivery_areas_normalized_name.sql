-- ============================================================================
-- 022 — بحث مناطق التوصيل يتحمّل اختلاف الإملاء العربي
-- ============================================================================
--
-- المشكلة:
-- أداة البوت find_delivery_area (مسار n8n «واتساب ذكي — متجر تشيرتات صيفية»)
-- كانت تبحث في delivery_areas.area_name بـ ilike حرفياً. فالزبون الذي يكتب
-- «القاهره» لا يطابق «القاهرة»، ولا «ديالي» يطابق «ديالى»، ولا «الاعظميه»
-- يطابق «الأعظمية».
--
-- الحل:
--   ١) الدالة ar_normalize توحّد الإملاء: تحذف التشكيل والتطويل وعلامات الاتجاه
--      الخفية، وتحوّل أ/إ/آ/ٱ ← ا، ى/ی/ئ ← ي، ة/ۀ/ۃ/ە/ھ ← ه، ؤ ← و، ک ← ك،
--      گ ← ق، ڤ ← ف، پ ← ب، چ ← ج، وتحذف الهمزة المنفردة.
--   ٢) العمود المحسوب area_name_norm = ar_normalize(area_name). يبحث فيه البوت
--      بعد أن يطبّق على نص الزبون **التحويل نفسه** بـ JavaScript (في تعبير
--      الأداة وفي عقدة Conversation Hints). أي تعديل على التحويل هنا يُعدَّل
--      هناك معه، وإلا انقطعت المطابقة بصمت.
--
-- الدليل جزئي: منطقة غير موجودة فيه تُقبل بالمحافظة التي يذكرها الزبون، والبوت
-- لا يقول له إنها «غير موجودة».
--
-- طُبِّق على الإنتاج أولاً في ٢٠٢٦-٠٩-٣٠ باسم delivery_areas_normalized_name،
-- ثم بهذا الملف: جسم الدالة نفسه لكن محارف التشكيل مكتوبة بترميز مرئي
-- (U&'\064B') بدل محارف خفية داخل النص، مع سحب صلاحية التنفيذ (نمط ٠١٣).
-- الترحيل قابل لإعادة التطبيق، وأُعيد تطبيقه على الإنتاج والمعاينة.
--
-- الرقم ٠٢١ محجوز لإلغاء استثناء «المتجر الأول» (انظر ٠٢٠).
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) دالة التطبيع
-- ----------------------------------------------------------------------------
create or replace function public.ar_normalize(t text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select btrim(regexp_replace(
    translate(
      -- التشكيل 064B–065F و0670، التطويل 0640، علامات الاتجاه الخفية 200B–200F و061C
      regexp_replace(coalesce(t, ''), U&'[\064B-\065F\0670\0640\200B-\200F\061C]', '', 'g'),
      -- ١٩ حرفاً مقابل ١٨: الأخير (ء) بلا مقابل فيُحذف
      'أإآٱىیئۀةۃەھؤکگڤپچء',
      'اااايييهههههوكقفبج'
    ),
    '\s+', ' ', 'g'
  ))
$$;

comment on function public.ar_normalize(text) is
  'توحيد الإملاء العربي لبحث المناطق (أ/إ/آ←ا، ى/ئ←ي، ة←ه، ؤ←و، گ←ق، چ←ج، بلا تشكيل). يطابقه JavaScript في مسار n8n للبوت — الترحيل ٠٢٢.';

-- ----------------------------------------------------------------------------
-- 2) العمود المحسوب
-- ----------------------------------------------------------------------------
alter table public.delivery_areas
  add column if not exists area_name_norm text
  generated always as (public.ar_normalize(area_name)) stored;

comment on column public.delivery_areas.area_name_norm is
  'ar_normalize(area_name): يبحث فيه بوت الواتساب حتى تتطابق ة/ه، ى/ي، أ/ا — الترحيل ٠٢٢.';

-- ----------------------------------------------------------------------------
-- 3) الصلاحيات
-- ----------------------------------------------------------------------------
-- العمود المحسوب يُقرأ مخزَّناً فلا تحتاج القراءة الدالة. الكتابة على
-- delivery_areas من service_role وحده (لا سياسة إدراج لغيره، الترحيل ٠١٢)،
-- وهو من يحتاج تنفيذ الدالة لحساب العمود.
revoke execute on function public.ar_normalize(text) from anon, authenticated, public;
grant execute on function public.ar_normalize(text) to service_role;

notify pgrst, 'reload schema';
