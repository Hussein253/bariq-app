-- ============================================================================
-- 014 — إسقاط المُحفِّز الذي كان يُنشئ صف الصلاحية تلقائياً
-- ============================================================================
--
-- ما كان يحدث: مُحفِّز on_auth_user_created على auth.users يستدعي
-- handle_new_user التي تُدرج في public.profiles صفاً بـ user_id و store_name
-- فقط — بلا role. كان ذلك يعمل حين كان للعمود قيمة افتراضية 'employee'.
--
-- الترحيل ٠١١ أسقط تلك القيمة الافتراضية **عمداً**: منح صلاحية ضمنياً لكل
-- حساب جديد هو بالضبط ما أردنا منعه. لكن المُحفِّز بقي، فصار يُدرج NULL في
-- عمود NOT NULL ويرمي:
--
--     null value in column "role" of relation "profiles" violates not-null
--
-- والأثر أن **كل إنشاء حساب يفشل** منذ تطبيق ٠١١ — من لوحة Supabase ومن
-- الـ API معاً. لم يُكتشف لأن الحسابات الثلاثة القائمة أُنشئت قبله، ولأن
-- الفشل يظهر كخطأ قاعدة بيانات غامض لا كرسالة مفهومة.
--
-- لماذا الإسقاط لا الإصلاح: أي قيمة افتراضية للدور قرارُ صلاحية يُتَّخذ
-- ضمنياً — staff يمنح أكثر من اللازم، و merchant يلزمه merchant_id فيكسر
-- قيد profiles_merchant_link_check. ولا تسجيل ذاتي في المنصة أصلاً، فلا
-- حاجة لمُحفِّز يخمّن. الأدوار تُمنح صريحةً بـ service_role من
-- lib/users-server.ts وحدها.
--
-- ماذا لو أُنشئ حساب بلا صف profiles بعد هذا الترحيل: getSessionProfile
-- يرفضه ويُنهي جلسته برسالة «حسابك غير مربوط بصلاحية بعد» — فشل مغلق
-- ومفهوم، لا صلاحية مُخمَّنة.
-- ============================================================================

drop trigger if exists on_auth_user_created on auth.users;
drop function if exists public.handle_new_user();

