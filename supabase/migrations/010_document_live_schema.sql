-- ----------------------------------------------------------------------------
-- 8) فرض حدود الباقة في قاعدة البيانات
--
-- الفرض هنا لا في الكود: مسار كتابة واحد يُنسى فيه الفحص يكفي لتجاوز الحدّ.
-- الدالة SECURITY DEFINER لأن الفحص يقرأ subscriptions و plans، وقد لا يملك
-- الدور المُنفِّذ صلاحية عليهما.
--
-- رموز الخطأ مُلتقَطة في lib/plan-limits.ts وتُترجم إلى ردود HTTP عربية:
--   BQ001 = تجاوز الحدّ (409)، BQ002 = لا اشتراك فعّال (402).
-- الرسالة تُرسَل وسوماً خاماً (BQ_LIMIT|التسمية|الحدّ) لا جملة جاهزة، لأن
-- قاعدة البيانات لا تعرف أن الواجهة تعرض أرقاماً عربية.
-- ----------------------------------------------------------------------------

create or replace function public.enforce_plan_limit()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_limit_column text := TG_ARGV[0];
  v_label        text := TG_ARGV[1];
  v_limit        int;
  v_count        int;
begin
  if NEW.merchant_id is null then
    return NEW;
  end if;

  -- قفل صف التاجر يُسلسل الإدخالات المتزامنة، فلا يمرّ طلبان معاً عند الحدّ
  perform 1 from public.merchants where id = NEW.merchant_id for update;

  execute format(
    'select p.%I
       from public.subscriptions s
       join public.plans p on p.id = s.plan_id
      where s.merchant_id = $1
        and s.status in (''trialing'',''active'',''past_due'')
      order by s.current_period_start desc
      limit 1',
    v_limit_column
  ) into v_limit using NEW.merchant_id;

  if v_limit is null then
    raise exception 'BQ_NO_SUBSCRIPTION|%', v_label using errcode = 'BQ002';
  end if;

  execute format('select count(*) from public.%I where merchant_id = $1', TG_TABLE_NAME)
    into v_count using NEW.merchant_id;

  if v_count >= v_limit then
    raise exception 'BQ_LIMIT|%|%', v_label, v_limit using errcode = 'BQ001';
  end if;

  return NEW;
end;
$function$;

revoke execute on function public.enforce_plan_limit() from public;
revoke execute on function public.enforce_plan_limit() from anon;
revoke execute on function public.enforce_plan_limit() from authenticated;

drop trigger if exists ai_agents_plan_limit on public.ai_agents;
