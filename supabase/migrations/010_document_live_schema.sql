-- ============================================================================
-- 010 — توثيق المخطط الحي: الجداول الـ ١٨ التي كانت تعيش في لوحة Supabase فقط
-- ============================================================================
--
-- المشكلة التي يحلّها هذا الملف:
-- كود المنصة يستعمل ٢٢ جدولاً، والترحيلات ٠٠١–٠٠٩ تنشئ أربعة منها فقط
-- (whatsapp_messages, merchants, couriers, shipments) وتضيف conversations و
-- messages. البقية أُنشئت يدوياً في لوحة Supabase ولم تُسجَّل في المستودع.
--
-- أثر ذلك عملياً:
--   • لا يمكن إنشاء بيئة اختبار أو تطوير مطابقة — أي مطوّر جديد يواجه
--     قاعدة ناقصة ومسارات تنهار بأخطاء "relation does not exist".
--   • لا استرجاع بعد خطأ: لا يوجد تعريف مرجعي يُعاد منه البناء.
--   • لا مراجعة على تغييرات المخطط: تعديل عمود مالي في اللوحة لا يمرّ بأي
--     مراجعة ولا يترك أثراً في تاريخ المستودع.
--   • مخالفة صريحة لبند ٢-ب (الهندسة أولاً) في CLAUDE.md.
--
-- طريقة التوليد: كل سطر هنا مُستخرَج من قاعدة البيانات الحية بالاستعلام عن
-- pg_catalog بتاريخ ٢٠٢٦-٠٩-١٥ — لا عمود ولا قيد ولا فهرس مكتوب من الذاكرة
-- أو مُخمَّن (بند ٢-أ، انعدام التخمين).
--
-- آمن للتشغيل على القاعدة الحية: كل شيء if not exists / or replace، ولا
-- يحذف ولا يغيّر أي بيانات قائمة. الغرض منه أن يصبح المستودع مصدر الحقيقة
-- للمخطط ابتداءً من اليوم.
--
-- ⚠️ ملاحظة درفت مرصودة: الترحيل ٠٠٢ يعرّف shipments.merchant_net_amount_iqd
-- بقيمة default، بينما العمود في القاعدة الحية GENERATED ALWAYS STORED.
-- النسخة الحية هي الصحيحة (الصافي يُشتق ولا يُخزَّن مُخمَّناً — بند ٤-٤)،
-- وهي المثبَّتة أدناه في القسم ٤.
-- ============================================================================

