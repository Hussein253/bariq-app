-- ============================================================================
--
-- الجدول public.delivery_areas (الترحيل ٠١٠) يقرؤه بوت المتجر بطريقتين:
--   • عقدة «Conversation Hints» (بالانستا «تلميحات المحادثة») تحمّل كل الصفوف
--     وتطابق بيها كلام الزبون، ومنه التفريغ الصوتي: تقترح الاسم الصحيح من الدليل
--     (حيدراب ← حي دراغ) وتعرف المحافظة قبل ما يسأل البوت الزبون «وين بالضبط؟».
--   • أداة find_delivery_area تبحث في area_name_norm (الترحيل ٠٢٢).
--
-- القسم ١: الصفوف الموجودة منقولة حرفياً من قاعدة الإنتاج (2026-10-03).
-- القسم ٢: الصفوف المضافة (طُبِّقت على الإنتاج 2026-10-03):
--   • الأقضية والنواحي من ويكيبيديا العربية «أقضية العراق» و«نواحي العراق»،
--     مكتوبة بلا كلمة «قضاء / ناحية».
--   • أحياء بغداد والبصرة والموصل وغيرها بأسمائها المتداولة.
--   • أجور التوصيل نفس تسعيرة صفوف الإنتاج بلا تخمين: كل صفوف بغداد ٣٬٠٠٠ وكل
--     صفوف باقي المحافظات ٥٬٠٠٠، فالصف الجديد ياخذ تسعيرة محافظته.
--   • تُركت عمداً أسماء هي كلمات يومية أو ألقاب (الفجر، الإمام، النيل، العبارة،
--     الصينية، الحيرة، الغالبية، العظيم ← «سد العظيم»، العباسي، الدراجي، النجمي)،
--     ونسخ المحافظات الثانية من أسماء بغدادية (المنصور واليرموك بالموصل، الحرية
--     بالنجف، العبيدي بالأنبار) حتى ما يُسأل زبون بغداد «يا محافظة؟» بلا داعي.
--   • الأسماء الباقية التي هي كلمات يومية أو أسماء أشخاص (الصدر، النصر، الفضل،
--     المنصور، القاسم، ربيعة…) تحرسها قوائم بعقدة التلميحات: ما تنحسب منطقة إلا
--     بقرينة مكان (بالفضل، منطقة النصر، بغداد الرشيد، الصدر قطاع ١٠).
--
-- حلبجة ونواحيها تحت «السليمانية» مثل صف حلبجة الموجود، حتى تبقى قيم المحافظة
-- كما هي (عقدة التلميحات تربط «حلبجة» بالسليمانية).
--
-- قابل لإعادة التشغيل: on conflict (area_name, governorate) do nothing — ما يغيّر
-- صفاً موجوداً ولا تسعيرته.
--
-- كيف يُشغَّل: Supabase Dashboard → SQL Editor، بعد الترحيلات حتى ٠٢٢.
