import { describe, expect, it } from 'vitest'
import { COMPLAINT_CUE_WORDS, hasComplaintCue, normCue } from '@/n8n/complaint-cues.js'

describe('hasComplaintCue — إنذارات التحويل الكاذبة الفعلية ما تمر', () => {
  // التحويلات الخمسة الي طلعت بالتنفيذات (كلها كانت خاطئة)
  it.each([
    'رايد قطعه من منتجكم', // التنفيذ 1573: «قطعة» = وحدة، مو قطعة غيار
    '(ستيكر 👍) شوكت يوصل ؟',
    '[رسالة صوتية]: ألو هل أنتم موجود أريد تثبيت الطلب',
    '[رسالة صوتية]: حبيبي مرتضى (كلمات بالصوت مو واضحة: «مرتضى»)',
    'منو وياي',
  ])('بدون كلمة شكوى: %s', (msg) => {
    expect(hasComplaintCue(msg)).toBe(false)
  })

  it.each([
    'تمام احجزلي الطلب',
    'اريد وحدة',
    'اريد قطعتين',
    'شكد سعر الغسالة؟',
    'شكد نسبه الخصم و شكد يصير السعر',
    'إذا القياس ما ضبط تبدلوه؟',
    'متى يوصل طلبي؟',
    'اكو توصيل لبغداد؟',
    'وصلني الطلب حلو كلش', // مدح بعد الاستلام
    'غالي، نزلي شوية',
  ])('أسئلة وطلبات عادية: %s', (msg) => {
    expect(hasComplaintCue(msg)).toBe(false)
  })

  it.each([
    'وصلني الطلب بس القياس غلط',
    'اللون مو نفس الي طلبته',
    'الغسالة خربانة ما تشتغل',
    'جاني ناقص قطعة من الطلب',
    'الطباعة باهتة وانكمش التيشيرت بعد الغسل',
    'الطلب متأخر لحد الان ما جاني',
    'المندوب ما اتصل بيّ',
    'المندوب طلب مني فلوس زايدة',
    'ما وصلني الطلب',
    'مو راضي عن الخدمة',
    'اريد استرجاع فلوسي',
    'اريد اشتكي',
    'عندي مشكلة بالطلب',
    'فيها خدش وعيب بالتصنيع',
  ])('شكوى حقيقية تمر: %s', (msg) => {
    expect(hasComplaintCue(msg)).toBe(true)
  })

  it('إملاء مختلف (همزة، تاء مربوطة، تشكيل) يطابق', () => {
    expect(hasComplaintCue('الطَلَب مُتأخّر')).toBe(true) // «متأخر» بتشكيل وهمزة
    expect(hasComplaintCue('خربانه')).toBe(true)
    expect(hasComplaintCue('مشكله')).toBe(true)
    expect(normCue('مُتأخّرة')).toBe('متاخره')
  })

  it('القائمة بصيغة موحّدة (بلا همزات ولا تاء مربوطة) وإلا ما تطابق نص موحّد', () => {
    for (const w of COMPLAINT_CUE_WORDS) expect(normCue(w)).toBe(w)
  })
})
