import { describe, expect, it } from 'vitest'
import { stripVoiceAck } from '@/n8n/voice-ack.js'

// رد البوت الفعلي على بصمة «شنو عندك من المنتجات وشنو ايام الدوام» (الداشبورد 2026-10-24)
const SCREENSHOT_REPLY = [
  'وصلتني البصمة، تسأل عن المنتجات وشنو أيام الدوام. عدنا غسالة أوتوماتيك ال جي 8 كيلو.',
  '',
  'أما بخصوص أيام الدوام، نحن من السبت للخميس من 10 ص لحد 11 م.',
  '',
  'إذا تحتاج تفاصيل إضافية أو معلومات عن المنتجات، أنا حاضر.',
  'STAGE: 1',
].join('\n')

describe('stripVoiceAck — الرد على البصمة يبدي بالجواب', () => {
  it('يشيل «وصلتني البصمة، تسأل عن …» ويخلي الجواب', () => {
    const out = stripVoiceAck(SCREENSHOT_REPLY)
    expect(out).not.toContain('وصلتني')
    expect(out).not.toContain('تسأل عن')
    expect(out.startsWith('عدنا غسالة أوتوماتيك ال جي 8 كيلو.')).toBe(true)
    expect(out).toContain('نحن من السبت للخميس من 10 ص لحد 11 م.')
    expect(out.endsWith('STAGE: 1')).toBe(true)
  })

  it.each([
    ['وصلتني الرسالة الصوتية، عدنا غسالة 8 كيلو.', 'عدنا غسالة 8 كيلو.'],
    ['تمام، وصلتني بصمتك، سعر الغسالة 350,000 دينار.', 'سعر الغسالة 350,000 دينار.'],
    ['سمعت بصمتك. عدنا غسالة 8 كيلو.', 'عدنا غسالة 8 كيلو.'],
    ['استلمت الفويس: التوصيل لبغداد ٥ آلاف.', 'التوصيل لبغداد ٥ آلاف.'],
    ['حاضر عيني، وصلتني البصمة وتسأل عن الأسعار. الغسالة بـ 350,000 دينار.', 'الغسالة بـ 350,000 دينار.'],
  ])('يشيل جملة الاستلام: %s', (reply, expected) => {
    expect(stripVoiceAck(reply)).toBe(expected)
  })

  it('يشيل سطر «وصلني الاسم والعنوان بالصوت» ويخلي الملخص والسؤال', () => {
    const reply = 'وصلني الاسم والعنوان بالصوت.\nطلبك هسة صار: غسالة LG 8 كيلو.\nتمام هيج؟\nSTAGE: 3'
    expect(stripVoiceAck(reply)).toBe('طلبك هسة صار: غسالة LG 8 كيلو.\nتمام هيج؟\nSTAGE: 3')
  })

  it('ما يلمس جملة التوضيح الي تنقل كلام الزبون بين «»', () => {
    const reply = 'عذراً منك عيني، البصمة ما وضحت عندي زين، وصلتني «هاي ضرغام». لو تتكرم تكتبلي شنو تقصد؟\nSTAGE: 1'
    expect(stripVoiceAck(reply)).toBe(reply)
  })

  it('ما يلمس سؤال التوضيح الكتابي ولا الأسطر المخفية', () => {
    const reply = 'عذراً منك عيني، البصمة ما وضحت عندي زين. لو تتكرم تكتبلي طلبك كتابة حتى أخدمك بدقة؟\nSTAGE: 1'
    expect(stripVoiceAck(reply)).toBe(reply)
  })

  it('جملة استلام ويا سؤال توضيح: يشيل الاستلام ويخلي السؤال', () => {
    expect(stripVoiceAck('وصلتني البصمة، بس ما وضح الاسم. شنو تقصد؟\nSTAGE: 1')).toBe('بس ما وضح الاسم. شنو تقصد؟\nSTAGE: 1')
  })

  it('إذا ما بقى غير جملة الاستلام يرجع الرد مثل ما هو (مو رد فاضي)', () => {
    const reply = 'وصلتني البصمة، تسأل عن المنتجات.'
    expect(stripVoiceAck(reply)).toBe(reply)
    const withStage = 'وصلتني البصمة.\nSTAGE: 1'
    expect(stripVoiceAck(withStage)).toBe(withStage)
  })

  it.each([
    'وصلني طلبي أمس بس القياس غلط.',
    'عدنا غسالة أوتوماتيك ال جي 8 كيلو.',
    'سمعت إن المنتج وصل للمخزن.',
    'الصوت واضح؟ اكتبلي كتابة لو تكدر.',
    '',
  ])('رد ما بيه جملة استلام يبقى مثل ما هو: %s', (reply) => {
    expect(stripVoiceAck(reply)).toBe(reply)
  })

  it('ما يخرّب الفراغات: بدون أسطر فاضية زايدة ولا فراغ بالبداية', () => {
    const out = stripVoiceAck('وصلتني البصمة، تسأل عن الدوام.\n\n\nدوامنا من السبت للخميس.\nSTAGE: 1')
    expect(out).toBe('دوامنا من السبت للخميس.\nSTAGE: 1')
  })
})
