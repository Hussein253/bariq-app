/** إملاء موحّد: بلا تشكيل، وهمزات وتاء مربوطة وألف مقصورة موحّدة */
export const normCue = (s) => String(s ?? '').replace(/\p{M}/gu, '').replace(/[أإآٱ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')

const RE = new RegExp(COMPLAINT_CUE_WORDS.join('|'))

/** @param {string} text رسائل الزبون الجديدة */
export const hasComplaintCue = (text) => RE.test(normCue(text))
