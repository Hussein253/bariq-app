/**
 * «تم تأكيد طلبك» قبل ما ينحفظ الطلب (2026-11-01): البوت يكول «تم تأكيد طلبك» بدون ما يستدعي create_order.
 * الزبون يصدّق، والطلب ما ينرسل للمندوب. الأمثلة الحقيقية:
 *   واتساب 09:44 و09:45: «تم عزيزي، تم تأكيد طلبك»، وما انحفظ أي طلب (ما انستدعى create_order بالتنفيذ).
 *   ماسنجر 13:28: «تم عزيزي، تم تأكيد طلبك. هودي شتوي، وحدة. وياريت تدزلي اسمك وعنوانك…»، وما انحفظ طلب.
 * بوابة ماسنجر الحالية تشتغل بس إذا الرد ينتهي بسؤال «أثبّتلك الطلب؟»، فالحالات الثانية تفوتها.
 *
 * الحارس: إذا ما انحفظ طلب بهالدور، كلمة «تم تأكيد طلبك» أو «طلبك هسة صار» تصير «هذا ملخص طلبك»،
 * وإذا قبلها «تم عزيزي» تصير «تمام عزيزي، هذا ملخص طلبك». إذا انحفظ الطلب، الرد يبقى كما هو.
 *
 * هذا الملف مصدر الكود: n8n/premature-confirm.mjs يزرعه بالحارس الأخير لكل القنوات، وtests/premature-confirm.test.ts يختبره.
 */

const FALSE_CONFIRM = [
  [/تم عزيزي[،,]?\s*تم تأكيد طلبك/g, 'تمام عزيزي، هذا ملخص طلبك'],
  [/تم عزيزتي[،,]?\s*تم تأكيد طلبك/g, 'تمام عزيزتي، هذا ملخص طلبك'],
  [/تم تأكيد طلبك/g, 'هذا ملخص طلبك'],
  [/تم عزيزي[،,]?\s*تم تثبيت طلبك/g, 'تمام عزيزي، هذا ملخص طلبك'],
  [/تم تثبيت طلبك/g, 'هذا ملخص طلبك'],
  [/طلبك هسة صار/g, 'هذا ملخص طلبك'],
]

/**
 * @param {string} text رد الوكيل (ويا الأسطر المخفية STAGE وNOTIFICATION_TYPE)
 * @param {boolean} orderCreated هل استدعى البوت create_order بهالدور (isExecuted)
 * @returns {string}
 */
export function prematureConfirmFix(text, orderCreated = false) {
  const src = String(text ?? '')
  if (orderCreated) return src
  let out = src
  for (const [re, to] of FALSE_CONFIRM) out = out.replace(re, () => to)
  return out
}
