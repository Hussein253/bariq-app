// (ماسنجر 2026-10-24، التنفيذ 1652: «ما ادري بعدين اشوف» ← «شكم وحدة تريد؟»)
const DEFER = /بعدين|لاحقا|ما ادري|خليني اشوف|اشوف بعدين|مو الان|مو هسه|ارجع لك|ارجعلك|افكر/

